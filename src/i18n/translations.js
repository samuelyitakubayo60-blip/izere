export function translate(lang, key) {
  const keys = key.split('.');
  const resolve = (tree) => {
    let value = tree;
    for (const k of keys) {
      value = value?.[k];
    }
    return typeof value === 'string' ? value : null;
  };
  return resolve(translations[lang]) ?? resolve(translations.en) ?? key;
}
